package main

import (
	"encoding/json"
	"os"
	"path/filepath"
)

// GenerateKeypair shells out to `wg genkey` / `wg pubkey`. The private key
// is captured from stdout and fed to `wg pubkey` over stdin — it never
// touches argv, per docs/arch/wireguard.md.
func GenerateKeypair() (privateKey, publicKey string, err error) {
	priv, err := runCmd("wg", "genkey")
	if err != nil {
		return "", "", err
	}
	pub, err := PublicKeyFromPrivate(priv)
	if err != nil {
		return "", "", err
	}
	return priv, pub, nil
}

// PublicKeyFromPrivate derives a public key from a private key via
// `wg pubkey`, feeding the key over stdin rather than argv.
func PublicKeyFromPrivate(privateKey string) (string, error) {
	return runCmdStdin(privateKey, "wg", "pubkey")
}

// EnsureKeys self-provisions a keypair into cfg if it doesn't already have
// one, persisting the generated private key back to path (preserving the
// file's existing 0600 mode). Returns the public key either way (derived
// from the existing key, or the newly generated one) so the caller can
// print it for the operator to hand to the other side, and whether a new
// key was generated.
func EnsureKeys(cfg *Config, path string) (publicKey string, generated bool, err error) {
	if cfg.PrivateKey != "" {
		pub, err := PublicKeyFromPrivate(cfg.PrivateKey)
		return pub, false, err
	}

	priv, pub, err := GenerateKeypair()
	if err != nil {
		return "", false, err
	}
	cfg.PrivateKey = priv
	if err := persistConfig(cfg, path); err != nil {
		return "", false, err
	}
	return pub, true, nil
}

// persistConfig writes cfg back to path as JSON, atomically: this file is
// the only copy of a WireGuard private key, so a crash or a full disk
// partway through the write must never leave it truncated or corrupted.
// Written to a temp file in the same directory (so the final rename is on
// the same filesystem) with 0600 set explicitly before the rename, since
// os.WriteFile's perm argument is only honored when creating a new file —
// it never changes an existing file's mode.
func persistConfig(cfg *Config, path string) error {
	data, err := json.MarshalIndent(cfg, "", "  ") //nolint:gosec // PrivateKey is deliberately serialized here; the file this writes to is always 0600 (see below)
	if err != nil {
		return err
	}

	tmp, err := os.CreateTemp(filepath.Dir(path), filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	defer func() { _ = os.Remove(tmpPath) }() //nolint:gosec // tmpPath is generated by os.CreateTemp next to the caller's own path, not external input; no-op once the rename below succeeds

	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o600); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpPath, path) //nolint:gosec // tmpPath is generated by os.CreateTemp next to the caller's own path, not external input
}
